"""P4: descriptive checks asked for by the internal review (paper/review_round1.md), from existing outputs only.

Usage: python src/p4_review_checks.py
Reads data/processed/forecast_h{3,5}_mean.csv (test rows, frozen GBT intervals) and the hand clicks (figures.clicks);
writes results/p4/review_checks.md. No model is refitted and no protocol choice is changed: these are post hoc,
descriptive breakdowns of the frozen H2 result, reported as such.
- Coverage of split / Mondrian GBT intervals by |Theil-Sen rate over the 10 years before the origin| (an input known
  at the origin), by series kind (defined from the whole 2000-2024 series, so not an input), and by forecast origin.
- Coverage of a zero-centred interval with the split half-width ("no change +- q").
- Click accuracy on the Tien split into the 45 Sa Dec-Cao Lanh clicks used to choose the bank rule and the rest.
CIs: 95% block bootstrap over 10 km blocks, 1000 resamples, seed 0 (as forecast.py).
"""
import pathlib
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from figures import clicks  # noqa: E402

OUT = pathlib.Path('results/p4/review_checks.md')
RATE_BINS, RATE_LABELS = [0, 1, 2, 5, 10, np.inf], ['< 1', '1-2', '2-5', '5-10', '> 10']


def boot(d, col, b=1000, seed=0):
    """Share of d[col] (0/1) in %, with a block-bootstrap CI over d.block."""
    g = d.groupby('block')[col].agg(['sum', 'count'])
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(g), (b, len(g)))
    s, n = g['sum'].to_numpy()[idx].sum(1), g['count'].to_numpy()[idx].sum(1)
    lo, hi = np.percentile(100 * s / n, [2.5, 97.5])
    return f'{100 * d[col].mean():.1f} [{lo:.1f}, {hi:.1f}]'


def table(d, by):
    rows = [f'| {k} | {len(x)} | {x.block.nunique()} | {boot(x, "cov_split")} | {boot(x, "cov_mondrian")} |'
            for k, x in d.groupby(by, observed=True)]
    return [f'| {by} | n | blocks | split | Mondrian |', '|---|---|---|---|---|'] + rows


def coverage(h):
    d = pd.read_csv(f'data/processed/forecast_h{h}_mean.csv')
    d = d[d.split.eq('test')].copy()
    for m in ('split', 'mondrian'):
        d[f'cov_{m}'] = d.y.between(d[f'lo_gbt_{m}'], d[f'hi_gbt_{m}']).astype(int)
    hw = (d.hi_gbt_split - d.lo_gbt_split) / 2
    d['cov_zero'] = (d.y.abs() <= hw).astype(int)
    d['rate_class'] = pd.cut(d.rate10.abs(), RATE_BINS, labels=RATE_LABELS, right=False)
    out = [f'## h = {h} yr (test rows {len(d)}, split half-width {hw.iloc[0]:.1f} m)', '',
           f'- Pooled: split {boot(d, "cov_split")}, Mondrian {boot(d, "cov_mondrian")}.',
           f'- Zero-centred interval 0 +- split half-width: {boot(d, "cov_zero")}.',
           f'- Rows with |rate10| >= 5 m/yr: split {boot(d[d.rate10.abs() >= 5], "cov_split")} '
           f'(n = {(d.rate10.abs() >= 5).sum()}); rate10 missing: {d.rate10.isna().sum()} rows.', '',
           '### By |Theil-Sen rate, 10 yr before the origin| (m/yr; known at the origin)', '']
    out += table(d, 'rate_class') + ['', '### By series kind (whole 2000-2024 series; not known at the origin)', '']
    out += table(d, 'kind') + ['', '### By forecast origin', ''] + table(d, 'origin') + ['']
    if h == 3:
        k = d.drop_duplicates(['channel', 'transect', 'side'])
        lin = k.groupby('group').kind.apply(lambda s: f'{100 * s.eq("linear").mean():.0f}%').to_dict()
        out += [f'Linear series among the {len(k)} transect sides with a test row: {100 * k.kind.eq("linear").mean():.0f}% '
                f'({", ".join(f"{g} {v}" for g, v in lin.items())}).', '']
    return out


def accuracy():
    def rmse(c):
        e = c.dist_m - c.user_dist_m
        return f'n = {len(e)}, RMSE {np.sqrt((e ** 2).mean()):.0f} m, median |error| {e.abs().median():.0f} m'
    dev = clicks('sadec_caolanh')
    ind = pd.concat([clicks('mythuan'), clicks('tien')])
    return ['## Tien click accuracy: development vs independent clicks', '',
            f'- Sa Dec-Cao Lanh (P0; used to choose the bank rule): {rmse(dev)}.',
            f'- My Thuan and new Tien reaches (not used for any choice): {rmse(ind)}.',
            f'- All: {rmse(pd.concat([dev, ind]))}.', '']


def main():
    lines = ['# P4: descriptive checks for the internal review', '',
             'Generated by `python src/p4_review_checks.py` from existing outputs (no refit; post hoc and descriptive, '
             'not part of the frozen protocol). Coverage = share of test rows whose observed retreat lies inside the '
             'frozen GBT 90% interval. CIs: 95% block bootstrap over 10 km blocks.', '']
    lines += coverage(3) + coverage(5) + accuracy()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(lines), encoding='utf-8')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
